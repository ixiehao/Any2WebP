export const languages = ["zh-CN", "en", "ja"];
const storageKey = "any2webp-language";
let preference = "system";
let locale = "en";

export function systemLanguage(preferred) {
  for (const choice of preferred) {
    const [language] = choice.toLowerCase().split(/[-_]/);
    if (language === "zh") return "zh-CN";
    if (languages.includes(language)) return language;
  }
  return "en";
}

export function savedLanguage() {
  try {
    return localStorage.getItem(storageKey) ?? "system";
  } catch {
    return "system";
  }
}

export function setLanguage(choice, preferred = navigator.languages, save = false) {
  preference = languages.includes(choice) ? choice : "system";
  locale = preference === "system" ? systemLanguage(preferred) : preference;
  if (save) {
    try { localStorage.setItem(storageKey, preference); } catch { /* use the session choice */ }
  }
  return { preference, locale };
}

export function currentLanguage() { return locale; }
export function currentPreference() { return preference; }

