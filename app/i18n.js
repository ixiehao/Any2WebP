export { catalog };
export const message = (key, args) => ({ key, args });

export function t(key, args = {}) {
  const row = catalog[key];
  if (!row) throw new Error("Unknown localization key: " + key);
  return row[languages.indexOf(locale)].replace(/\{(\w+)\}/g, (_, name) => args[name] ?? "");
}

export function messageText(value) {
  if (Array.isArray(value)) return value.filter(Boolean).map(messageText).join(" · ");
  return value?.key ? t(value.key, value.args) : value ?? "";
}

export function errorMessage(error) {
  const raw = error instanceof Error ? error.message : String(error);
  const packet = /^ui:([a-zA-Z]+)(?::([\s\S]+))?$/.exec(raw);
  if (!packet || !Object.hasOwn(catalog, packet[1])) return message("errorDetail", { detail: raw });
  const label = message(packet[1]);
  return packet[2] ? [label, packet[2]] : label;
}
